"""Evaluation-2 numbers for the paper, generated from report.json (paper draft 9 outline, "Rules for the text").

--write flattens report.json into one LaTeX macro per path: the text writes \\rv{q4.k} or \\rv{q1.tests.C*-F111|D2+H3.estimate}.
--check fails when a path used in the text is not in the report, when numbers.tex is stale, or when a bare decimal
number (decimal, integer, or percentage, outside identifiers such as F111) appears between `% BEGIN-EV2` and `% END-EV2` (evaluation-2 result text must use macros)."""
from __future__ import annotations

import argparse
import json
import math
import re
import sys
from pathlib import Path

DIGITS = 3
BARE = re.compile(r"(?<![A-Za-z0-9_.])-?(?:\d+(?:\.\d+)?|\.\d+)%?")       # decimals, integers, percentages; not F111, X7-SC, D2+H3
# Stripped before the bare-number scan: \const{} (protocol constants, marked explicitly) and arguments of references.
EXEMPT = re.compile(r"\\(?:const|evone)\{[^}]*\}|\\(?:ref|eqref|cite|citep|citet|label|input|include|includegraphics|url|href)(?:\[[^\]]*\])?\{[^}]*\}")
USE = re.compile(r"\\rv\{([^}]*)\}")
USEK = re.compile(r"\\rvk\{(\w+)\}\{([^}]*)\}")
SITE = re.compile(r"\\site\{([^}]*)\}")
SECTION = re.compile(r"\\section\*?\{([^}]*)\}(?:\\label\{sec:([^}]*)\})?")
FULL = ("abstract", "results")       # sections that must lie wholly inside result regions
NOBARE = REQUIRED = ("abstract", "intro", "results", "discussion", "conclusion")   # no unmarked number outside regions; captions likewise
LABEL = re.compile(r"\\label\{sec:([^}]*)\}")
COMMENT = re.compile(r"(?<!\\)%.*")
INPUT = re.compile(r"\\(?:input|include)\{([^}]*)\}")
P_LEAVES = {"p", "p_gain", "p_eff"}
# Kinds for prose in result regions: the field name and the value type must fit the sentence's statistic.
KINDS = {"count": lambda leaf, v: leaf == "k" and isinstance(v, int) and not isinstance(v, bool),
         "p": lambda leaf, v: leaf in P_LEAVES and isinstance(v, float) and 0 <= v <= 1,
         "gain": lambda leaf, v: leaf in {"estimate", "gain_diff", "gain_diff_lower", "attacker_gain", "0", "1"} and isinstance(v, float),
         "eff": lambda leaf, v: leaf in {"eff", "eff_lower", "efficiency", "0", "1"} and isinstance(v, float),
         "label": lambda leaf, v: isinstance(v, str)}
HEADER = "% Generated by docs/revision/paper-v2/numbers_v2.py from report.json; do not edit.\n"
PREAMBLE = "\\providecommand{\\const}[1]{#1}\n\\providecommand{\\evone}[1]{#1}\n\\providecommand{\\rvk}[2]{\\rv{#2}}\n\\providecommand{\\site}[1]{\\ifcsname site@#1\\endcsname\\csname site@#1\\endcsname\\else\\textbf{??#1}\\fi}\n\\providecommand{\\rv}[1]{\\ifcsname rv@#1\\endcsname\\csname rv@#1\\endcsname\\else\\textbf{??#1}\\fi}\n"


def _fmt(v) -> str:
    if v is None:
        return "n/a"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        if not math.isfinite(v):
            raise ValueError(f"nonfinite value in the report: {v}")
        s = f"{v:.{DIGITS}f}"
        return f"\\ensuremath{{{s}}}" if s.startswith("-") else s
    return re.sub(r"([&%$#_{}])", r"\\\1", str(v))


def _fmt_p(v) -> str:
    """p-values: four significant digits; small values in scientific form, so a nonzero p never prints as 0.000."""
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        return _fmt(v)
    if not math.isfinite(v):
        raise ValueError(f"nonfinite value in the report: {v}")
    s = f"{float(v):.4g}"
    if "e" in s:
        m, e = s.split("e")
        return f"\\ensuremath{{{m}\\times10^{{{int(e)}}}}}"
    return s


def flat(report, prefix: str = "") -> dict:
    """Report path to raw value."""
    out = {}
    items = report.items() if isinstance(report, dict) else enumerate(report)
    for k, v in items:
        path = f"{prefix}{k}"
        out.update(flat(v, path + ".")) if isinstance(v, (dict, list)) else out.__setitem__(path, v)
    return out


def _is_p(path: str) -> bool:
    parts = path.split(".")
    return parts[-1] in P_LEAVES or (len(parts) >= 2 and parts[-2] in P_LEAVES)


def macros(report: dict) -> dict:
    return {p: (_fmt_p(v) if _is_p(p) else _fmt(v)) for p, v in flat(report).items()}


def render(report: dict, sites: dict | None = None) -> str:
    m = macros(report)
    lines = [f"\\expandafter\\def\\csname rv@{p}\\endcsname{{{v}}}" for p, v in sorted(m.items())]
    lines += [f"\\expandafter\\def\\csname site@{n}\\endcsname{{{m.get(d['path'], '??' + n)}}}" for n, d in sorted((sites or {}).items())]
    return HEADER + PREAMBLE + "\n".join(lines) + "\n"


def _sites(path) -> dict | None:
    """The result-site manifest: site name -> {path, kind, section}; read from beside the given file when present."""
    f = Path(path).parent / "sites.json"
    return json.loads(f.read_text()) if f.exists() else None


def write(report_path, numbers_path) -> None:
    Path(numbers_path).write_text(render(json.loads(Path(report_path).read_text()), _sites(numbers_path)))


def _blocks(tex: str) -> tuple[list[str], list[str]]:
    blocks, problems, cur = [], [], None
    for n, line in enumerate(tex.splitlines(), 1):
        s = line.strip()
        if s == "% BEGIN-EV2":
            if cur is not None:
                problems.append(f"line {n}: nested BEGIN-EV2")
            cur = []
        elif s == "% END-EV2":
            if cur is None:
                problems.append(f"line {n}: END-EV2 without BEGIN-EV2")
            else:
                blocks.append("\n".join(cur)); cur = None
        elif cur is not None and not s.startswith("%"):
            cur.append(line)
    if cur is not None:
        problems.append("unclosed BEGIN-EV2 block")
    return blocks, problems


def strip_comments(text: str) -> str:
    """Remove LaTeX comments (a % after an even number of backslashes), keeping the region marker lines."""
    out = []
    for line in text.splitlines():
        if line.strip() in ("% BEGIN-EV2", "% END-EV2"):
            out.append(line.strip()); continue
        cut, i = len(line), 0
        while i < len(line):
            if line[i] == "%":
                k = i
                while k > 0 and line[k - 1] == "\\":
                    k -= 1
                if (i - k) % 2 == 0:
                    cut = i; break
            i += 1
        out.append(line[:cut])
    return "\n".join(out) + "\n"


def sources(tex_path, numbers_path=None) -> str:
    """The text with every \\input or \\include file inlined, except the generated numbers file and generated tables
    (checked by tables_v2.py --check)."""
    base = Path(tex_path).parent; skip = {Path(numbers_path).name} if numbers_path else set()
    def inline(m):
        name = m.group(1); f = base / (name if name.endswith(".tex") else name + ".tex")
        if f.name in skip or name.startswith("tables/") or not f.exists():
            return m.group(0)
        return sources(f, numbers_path)
    return INPUT.sub(inline, strip_comments(Path(tex_path).read_text()))      # comments first: a commented \\input is not followed


def _report_numbers(raw: dict) -> set:
    return {f"{v:.3f}" for v in raw.values() if isinstance(v, float) and not isinstance(v, bool) and math.isfinite(v)}


def check(report_path, numbers_path, tex_path) -> list[str]:
    report = json.loads(Path(report_path).read_text()); known = macros(report); raw = flat(report)
    tex = sources(tex_path, numbers_path); problems = []
    sites = _sites(tex_path)
    if not Path(numbers_path).exists() or Path(numbers_path).read_text() != render(report, sites):
        problems.append(f"{numbers_path}: stale or missing; run --write")
    used = set(USE.findall(tex)) | {p for _, p in USEK.findall(tex)}
    problems += [f"unknown report path in the text: {p}" for p in sorted(used) if p not in known]
    for kind, p in USEK.findall(tex):
        if kind not in KINDS:
            problems.append(f"unknown kind {kind} for {p}")
        elif p in raw and not KINDS[kind](p.split(".")[-1], raw[p]):
            problems.append(f"kind {kind} does not fit {p} (value {raw[p]!r})")
    blocks, bp = _blocks(tex); problems += bp
    for b in blocks:
        problems += [f"plain \\rv in an evaluation-2 block (use \\rvk with a kind): {p}" for p in USE.findall(b)]
        bare = BARE.findall(EXEMPT.sub("", USEK.sub("", USE.sub("", b))))
        problems += [f"bare number in an evaluation-2 block: {x}" for x in bare]
    outside = tex
    for b in blocks:
        outside = outside.replace(b, "")
    if sites is not None:
        return problems + _site_checks(tex, sites, raw, known, outside)
    vals = _report_numbers(raw)
    for x in BARE.findall(EXEMPT.sub("", USEK.sub("", USE.sub("", outside)))):
        if re.fullmatch(r"-?\d*\.\d{3,}", x) and f"{float(x):.3f}" in vals:
            problems.append(f"number outside the evaluation-2 regions equals a report value (mark it, or wrap evaluation-1 values in \\evone): {x}")
    return problems


def _scan(tex: str):
    """Per line of comment-free text: (section key, inside a result region, text), and problems. Every \\section needs
    a \\label{sec:...} on its line or the next; sec: labels elsewhere are refused and do not change the section."""
    sec, region, out, problems, pending = "front", False, [], [], None
    for line in tex.splitlines():
        s = line.strip()
        if s == "% BEGIN-EV2":
            region = True; continue
        if s == "% END-EV2":
            region = False; continue
        m = SECTION.search(line); lab = LABEL.search(line)
        if pending is not None and not m:
            if lab:
                sec = lab.group(1); lab = None
            elif s:
                problems.append(f"section without a \\label{{sec:...}}: {pending}"); sec = pending.lower()
            pending = None if (s or sec != "front") else pending
        if s.startswith("\\begin{abstract}"):
            sec = "abstract"
        elif m:
            if m.group(2):
                sec = m.group(2)
            else:
                pending = m.group(1).strip(); sec = pending.lower()
        elif lab:
            problems.append(f"sec: label outside a section heading: {lab.group(1)}")
        out.append((sec, region, line))
    if pending is not None:
        problems.append(f"section without a \\label{{sec:...}}: {pending}")
    return out, problems


def _captions(tex: str) -> list[tuple[bool, str]]:
    """Whole \\caption arguments (brace-matched across lines), each with whether it starts inside a result region."""
    region, spans, pos = False, [], 0
    for line in tex.splitlines(keepends=True):
        s = line.strip()
        if s == "% BEGIN-EV2":
            region = True
        elif s == "% END-EV2":
            region = False
        spans.append((pos, region)); pos += len(line)
    def inside(off):
        r = False
        for start, reg in spans:
            if start > off:
                break
            r = reg
        return r
    out = []
    for m in re.finditer(r"\\caption(?:\[[^\]]*\])?\{", tex):
        depth, k = 1, m.end()
        while k < len(tex) and depth:
            depth += {"{": 1, "}": -1}.get(tex[k], 0) if tex[k - 1] != "\\" else 0; k += 1
        out.append((inside(m.start()), tex[m.end():k - 1]))
    return out


def _site_checks(tex: str, sites: dict, raw: dict, known: dict, outside: str) -> list[str]:
    problems = []
    for n, d in sorted(sites.items()):
        if d.get("path") not in known:
            problems.append(f"site {n}: report path {d.get('path')} not in the report")
        elif d.get("kind") not in KINDS or not KINDS[d["kind"]](d["path"].split(".")[-1], raw[d["path"]]):
            problems.append(f"site {n}: kind {d.get('kind')} does not fit {d['path']}")
    seen = {}; scanned, sp = _scan(tex); problems += sp
    keys = {sec for sec, _, _ in scanned}
    problems += [f"required section {k} (\\label{{sec:{k}}}) not found" for k in REQUIRED if k not in keys]
    for in_region, cap in _captions(tex):
        if not in_region and (BARE.findall(EXEMPT.sub("", cap)) or USE.search(cap) or USEK.search(cap) or SITE.search(cap)):
            problems.append(f"caption outside a result region holds a number or result macro: {' '.join(cap.split())[:80]}")
    for sec, region, line in scanned:
        for n in SITE.findall(line):
            seen.setdefault(n, []).append(sec)
            if n not in sites:
                problems.append(f"unknown site in the text: {n}")
            elif sec != sites[n]["section"]:
                problems.append(f"site {n} is in section {sec}, declared in section {sites[n]['section']}")
            if not region:
                problems.append(f"site {n} is outside a result region")
        if region and (USE.search(line) or USEK.search(line)):
            problems.append(f"raw report path in a result region (use \\site): {line.strip()[:80]}")
        s = line.strip()
        if sec in FULL and not region and s and not s.startswith("%") and not SECTION.search(s) \
                and not re.fullmatch(r"\\(begin|end)\{abstract\}|\\label\{[^}]*\}", s):
            problems.append(f"text outside a result region in section {sec}: {s[:80]}")
        if not region and sec in NOBARE:
            problems += [f"unmarked number outside the result regions in section {sec} (use \\site, \\evone, or \\const): {x}"
                         for x in BARE.findall(EXEMPT.sub("", line))]
    problems += [f"site {n} used twice ({len(v)} times)" for n, v in sorted(seen.items()) if len(v) > 1 and n in sites]
    problems += [f"site {n} unused" for n in sorted(sites) if n not in seen]
    for x in BARE.findall(EXEMPT.sub("", outside)):
        if re.fullmatch(r"-?\d*\.\d{3,}", x):
            problems.append(f"unmarked number with three or more decimals outside the result regions (wrap it in \\evone or \\const): {x}")
    return problems


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", required=True); ap.add_argument("--numbers", required=True)
    g = ap.add_mutually_exclusive_group(required=True); g.add_argument("--write", action="store_true"); g.add_argument("--check", metavar="TEX")
    a = ap.parse_args(argv)
    if a.write:
        write(a.report, a.numbers); return 0
    problems = check(a.report, a.numbers, a.check)
    if _sites(a.check) is None:
        problems.insert(0, "sites.json (the result-site manifest) is required beside the paper source")
    print("\n".join(problems) or "ok")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
